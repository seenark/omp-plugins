import { IMPORT_MAP, PSTACK_LICENSE, TEAM_KIT_LICENSE } from "./source.ts";
import type { Exclusion, Pin } from "./types.ts";

const BEGIN = "# BEGIN pstack sync (generated by src/sync; do not edit)";
const END = "# END pstack sync";
const HEADER = "Third-party notices for @codesook/omp-pstack\n\n";
const RULE = "=".repeat(70);
const THIN_RULE = "-".repeat(70);

export interface NoticeInput {
	pin: Pin;
	exclusions: readonly Exclusion[];
	licenses: { pstack: string; teamKit: string };
}

function block({ pin, exclusions, licenses }: NoticeInput): string {
	const imports = IMPORT_MAP.map(({ from, to }) => `  ${to}**  <-  ${from}**`);
	const excluded = exclusions.map(({ path }) => `  ${path}`);
	return [
		BEGIN,
		RULE,
		"pstack (Upstream)",
		RULE,
		"",
		`Upstream: cursor/plugins, pstack component (pstack ${pin.version}, author Lauren Tan)`,
		`Pinned Revision: ${pin.revision}`,
		`URL: ${pin.repository}/tree/${pin.revision}/pstack`,
		"deslop: cursor-team-kit component of the same repository, at the same Pinned Revision.",
		"",
		"Vendored Content, adapted by src/sync (Adaptations are listed in README.md):",
		...imports,
		"",
		"Excluded from Vendored Content:",
		...excluded,
		"  (every other Upstream path, including pstack/automations, pstack/docs, thermos and",
		"  the other cursor-team-kit skills, is never imported)",
		"",
		"Licenses: MIT, Upstream LICENSE files verbatim below.",
		"",
		THIN_RULE,
		`${PSTACK_LICENSE} (pstack, Lauren Tan)`,
		THIN_RULE,
		"",
		licenses.pstack.trim(),
		"",
		THIN_RULE,
		`${TEAM_KIT_LICENSE} (cursor-team-kit, Cursor; applies to deslop)`,
		THIN_RULE,
		"",
		licenses.teamKit.trim(),
		END,
	].join("\n");
}

/** Replaces the generated block, leaving any text around it (other attributions) untouched. */
export function renderNotices(existing: string | undefined, input: NoticeInput): string {
	const generated = block(input);
	if (existing === undefined) return `${HEADER}${generated}\n`;
	const start = existing.indexOf(BEGIN);
	const finish = existing.indexOf(END);
	if (start === -1 || finish === -1 || finish < start) return `${existing.trimEnd()}\n\n${generated}\n`;
	return `${existing.slice(0, start)}${generated}${existing.slice(finish + END.length)}`;
}
